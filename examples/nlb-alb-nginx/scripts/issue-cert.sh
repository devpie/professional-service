# Replace the self-signed ALB certificate with a valid Let's Encrypt certificate.
#
# Run after the first `terraform apply` (the STACKIT DNS zone must exist).
# Uses certbot with the STACKIT DNS plugin (DNS-01 challenge), stores everything
# in .certbot/ in the repo and writes certbot.auto.tfvars, so every following
# `terraform apply` uses the new certificate.
#
# Run again for renewal (Let's Encrypt certificates are valid for 90 days);
# certbot only renews if the certificate expires within 30 days.
#
# Environment variables:
#   SA_KEY        service account key JSON with DNS permissions (default: /root/.stackit/credentials.json)
#   EMAIL         e-mail for Let's Encrypt expiry notices (optional)
#   STAGING=1     use the Let's Encrypt staging CA (untrusted certificate, for testing)
#   PROPAGATION   seconds to wait for DNS propagation (default: 300)
#   AUTO_APPROVE=1  run terraform apply without confirmation
set -euo pipefail

cd "$(dirname "$0")/.."
REPO_DIR=$(pwd)
CERTBOT_DIR="$REPO_DIR/.certbot"
SA_KEY=${SA_KEY:-/root/.stackit/credentials.json}
PROPAGATION=${PROPAGATION:-300}

FQDN=$(terraform output -raw fqdn)
PROJECT_ID=$(terraform output -raw project_id)

if [ "${STAGING:-0}" = "1" ]; then
  SERVER=https://acme-staging-v02.api.letsencrypt.org/directory
  CERT_NAME="$FQDN-staging"
else
  SERVER=https://acme-v02.api.letsencrypt.org/directory
  CERT_NAME="$FQDN"
fi

if [ -n "${EMAIL:-}" ]; then
  ACCOUNT_ARGS=(--email "$EMAIL")
else
  ACCOUNT_ARGS=(--register-unsafely-without-email)
fi

# certbot with STACKIT DNS plugin in a local virtualenv
if [ ! -x "$CERTBOT_DIR/venv/bin/certbot" ]; then
  echo "Installing certbot and certbot-dns-stackit into $CERTBOT_DIR/venv"
  python3 -m venv "$CERTBOT_DIR/venv"
  "$CERTBOT_DIR/venv/bin/pip" install --quiet certbot certbot-dns-stackit
fi

echo "Requesting certificate for $FQDN (project $PROJECT_ID), waiting ${PROPAGATION}s for DNS propagation"
"$CERTBOT_DIR/venv/bin/certbot" certonly \
  --non-interactive \
  --agree-tos \
  "${ACCOUNT_ARGS[@]}" \
  --server "$SERVER" \
  --config-dir "$CERTBOT_DIR/config" \
  --work-dir "$CERTBOT_DIR/work" \
  --logs-dir "$CERTBOT_DIR/logs" \
  --authenticator dns-stackit \
  --dns-stackit-project-id "$PROJECT_ID" \
  --dns-stackit-service-account "$SA_KEY" \
  --dns-stackit-propagation-seconds "$PROPAGATION" \
  --cert-name "$CERT_NAME" \
  --keep-until-expiring \
  -d "$FQDN"

LIVE_DIR="$CERTBOT_DIR/config/live/$CERT_NAME"
cat > certbot.auto.tfvars <<EOF
# Generated by scripts/issue-cert.sh. Delete this file to go back to the self-signed certificate.
tls_cert_file = "$LIVE_DIR/fullchain.pem"
tls_key_file  = "$LIVE_DIR/privkey.pem"
EOF
echo "Wrote certbot.auto.tfvars"

if [ "${AUTO_APPROVE:-0}" = "1" ]; then
  terraform apply -auto-approve
else
  terraform apply
fi
